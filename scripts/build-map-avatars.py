"""Generate small inline map avatars from the existing hospital card assets."""
from pathlib import Path
from PIL import Image, ImageOps
import base64, io, json
root = Path(__file__).resolve().parents[1]
rows = {}
for i in range(8):
    key = 'f1_imgNhBnhVin' + (str(i) if i else '')
    with Image.open(root / 'apps/mobile/src/assets/discovery' / (key + '.png')) as src:
        image = src.convert('RGB')
        image = ImageOps.contain(image, (96, 96)) if i in (3, 5) else ImageOps.fit(image, (96, 96))
        canvas = Image.new('RGB', (96, 96), 'white')
        canvas.paste(image, ((96-image.width)//2, (96-image.height)//2))
        output = io.BytesIO()
        canvas.save(output, format='JPEG', quality=82, optimize=True)
        rows[key] = 'data:image/jpeg;base64,' + base64.b64encode(output.getvalue()).decode()
(root / 'apps/mobile/src/components/maps/hospital-avatars.ts').write_text('// Generated by scripts/build-map-avatars.py; source: existing hospital card assets.\nexport const hospitalAvatars:Record<string,string>=' + json.dumps(rows) + ';\n')
