import {test,expect} from './fixtures.mjs';
test.use({viewport:{width:390,height:844}});
test('forgot password -> email OTP -> new password -> login',async({page,request})=>{
 const email=`reset-ui-${Date.now()}@example.com`,password='original-ui-test-password',newPassword='changed-ui-test-password';
 async function codeFromMail(subject){const mailbox=await(await request.get('http://127.0.0.1:8025/api/v1/messages')).json();const message=mailbox.messages.find(m=>m.To.some(to=>to.Address===email)&&m.Subject===subject);expect(message).toBeTruthy();const content=await(await request.get('http://127.0.0.1:8025/api/v1/message/'+message.ID)).json();return content.Text.match(/\b\d{6}\b/)[0];}
 const registration=await request.post('http://127.0.0.1:3002/api/v1/auth/register',{data:{email,password,name:'Reset UI test'}});expect(registration.status()).toBe(202);
 const challenge=await registration.json();const registrationCode=await codeFromMail('Mã xác thực tài khoản UX_UI');
 expect((await request.post('http://127.0.0.1:3002/api/v1/auth/verify',{data:{challengeId:challenge.challengeId,code:registrationCode}})).status()).toBe(200);
 page.on('dialog',dialog=>dialog.accept());
 await page.goto('http://127.0.0.1:8081/sign-in');
 await page.getByRole('button',{name:'Quên mật khẩu?',exact:true}).click();
 await expect(page.getByText('Khôi phục tài khoản',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Email',exact:true}).filter({visible:true}).fill(email);
 await page.getByRole('button',{name:'Gửi mã xác thực',exact:true}).click();
 await expect(page.getByText('Kiểm tra email của bạn',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Mã xác thực 6 chữ số',exact:true}).fill(await codeFromMail('Khôi phục mật khẩu UX_UI'));
 await page.getByRole('button',{name:'Xác thực',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Mật khẩu mới',exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Mật khẩu mới',exact:true}).fill(newPassword);
 await page.getByRole('textbox',{name:'Nhập lại mật khẩu mới',exact:true}).fill('does-not-match');
 await page.getByRole('button',{name:'Lưu mật khẩu mới',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('chưa trùng nhau');
 await page.getByRole('textbox',{name:'Nhập lại mật khẩu mới',exact:true}).fill(newPassword);
 await page.screenshot({path:'.local/screenshots/new-password-390.png',fullPage:true});
 await page.getByRole('button',{name:'Lưu mật khẩu mới',exact:true}).click();
 await expect(page.getByText('Chào mừng bạn trở lại!')).toBeVisible();
 await page.getByRole('textbox',{name:'Email',exact:true}).filter({visible:true}).fill(email);
 await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('không đúng');
 await page.getByLabel('Mật khẩu',{exact:true}).fill(newPassword);
 await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
 await expect(page.getByText('Vị trí của bạn ở đâu?',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Bỏ qua vị trí',exact:true}).click();
 await page.getByRole('button',{name:'Để sau',exact:true}).click();
 await expect(page.getByText('Bạn chưa có lịch hẹn sắp tới',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Tài khoản',exact:true}).click();
 await expect(page.getByText(email,{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();
 await expect(page.getByText('Chào mừng bạn trở lại!',{exact:true})).toBeVisible();
});
